
class StringAPIExample{
public static void main(String[] args){
	String name = "avikaPglu"; //string litral
	//String address = new String("hi");
	System.out.println(name.length());//length 
	System.out.println(name.toUpperCase());//uppercase 
	System.out.println(name.toLowerCase());//lowercase 
	System.out.println(name.equals("java Programming"));//true
	System.out.println(name.charAt(5));//p
	System.out.println(name.substring(5));//programming
	System.out.println(name.substring(0,4));//java
	System.out.println(name.contains("java"));
	

}
}